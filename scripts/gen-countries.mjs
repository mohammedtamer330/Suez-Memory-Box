import fs from "node:fs";
const codes = fs.readdirSync("public/flags").filter(f=>/^[a-z]{2}\.svg$/.test(f)).map(f=>f.slice(0,2).toUpperCase());
const dn = new Intl.DisplayNames(["en"],{type:"region"});
const ok = codes.filter(c=>{ try { const n=dn.of(c); return n && n!==c && c!=="XX"; } catch { return false; } }).sort((a,b)=>dn.of(a).localeCompare(dn.of(b)));
// Names are frozen at generation time: Intl.DisplayNames differs between Node and browsers ("Hong Kong SAR China" vs "Hong Kong"),
// which would cause hydration mismatches.
const names = Object.fromEntries(ok.map(c=>[c, dn.of(c)]));
fs.writeFileSync("lib/country-codes.ts", `// Generated by scripts/gen-countries.mjs — ISO 3166-1 alpha-2 codes that have a bundled flag SVG in /public/flags.\nexport const COUNTRY_CODES: readonly string[] = ${JSON.stringify(ok)};\nexport const COUNTRY_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(names)};\n`);
console.log(ok.length, "countries");
